\set ON_ERROR_STOP on

-- Run with: psql -U postgres -d netlogs -f sql/fail_analysis.sql
-- Pattern mismatches are saved in logs.errorformats. Re-running also increments counters.

BEGIN;

CREATE TABLE IF NOT EXISTS logs.username (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    n BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS logs.sourceip (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    addr INET NOT NULL UNIQUE,
    n BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS logs.protocol (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    n BIGINT NOT NULL DEFAULT 1
);

ALTER TABLE logs.username
    ADD COLUMN IF NOT EXISTS n BIGINT NOT NULL DEFAULT 1;
ALTER TABLE logs.sourceip
    ADD COLUMN IF NOT EXISTS n BIGINT NOT NULL DEFAULT 1;
ALTER TABLE logs.protocol
    ADD COLUMN IF NOT EXISTS n BIGINT NOT NULL DEFAULT 1;

CREATE TABLE IF NOT EXISTS logs.errorformats (
    str TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS logs.fail (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tried_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    uid BIGINT REFERENCES logs.username (id),
    sid BIGINT REFERENCES logs.sourceip (id),
    client_ip INET,
    tr TEXT,
    rr TEXT,
    pid BIGINT REFERENCES logs.protocol (id)
);

CREATE TEMP TABLE fail_log_raw ON COMMIT DROP AS
SELECT
    content,
    regexp_match(
        content,
        $pattern$Date:[[:space:]]*([^,]+),[[:space:]]+.*Username:[[:space:]]*(.*),[[:space:]]+Source:[[:space:]]*([^,]*),[[:space:]]+Client IP:[[:space:]]*([^,]*),[[:space:]]+Transmission rate:[[:space:]]*([^,]*),[[:space:]]+Receiving rate:[[:space:]]*([^,]*),[[:space:]]+Protocol:[[:space:]]*([^,]*),[[:space:]]+Connection status:[[:space:]]*Login Fail\.$pattern$,
        'i'
    ) AS fields
FROM logs.w20261123_13_36_23
WHERE service = 'QVPN Service'
  AND category = 'VPN Server'
  AND content ILIKE '%Connection status: Login Fail.%';

INSERT INTO logs.errorformats (str)
SELECT content
FROM fail_log_raw
WHERE fields IS NULL OR cardinality(fields) <> 7;

CREATE TEMP TABLE fail_log_parsed ON COMMIT DROP AS
SELECT
    to_timestamp(btrim(fields[1]), 'YYYY/MM/DD HH24:MI:SS')::timestamp
        AS tried_at,
    NULLIF(btrim(fields[2]), '') AS username,
    NULLIF(NULLIF(btrim(fields[3]), ''), '---')::inet AS source_addr,
    NULLIF(NULLIF(btrim(fields[4]), ''), '---')::inet AS client_ip,
    NULLIF(btrim(fields[5]), '') AS tr,
    NULLIF(btrim(fields[6]), '') AS rr,
    NULLIF(btrim(fields[7]), '') AS protocol_name
FROM fail_log_raw
WHERE fields IS NOT NULL
  AND cardinality(fields) = 7;

INSERT INTO logs.username AS existing (name, n)
SELECT username, count(*)::bigint
FROM fail_log_parsed
WHERE username IS NOT NULL
GROUP BY username
ON CONFLICT (name) DO UPDATE
SET n = existing.n + EXCLUDED.n;

INSERT INTO logs.sourceip AS existing (addr, n)
SELECT source_addr, count(*)::bigint
FROM fail_log_parsed
WHERE source_addr IS NOT NULL
GROUP BY source_addr
ON CONFLICT (addr) DO UPDATE
SET n = existing.n + EXCLUDED.n;

INSERT INTO logs.protocol AS existing (name, n)
SELECT protocol_name, count(*)::bigint
FROM fail_log_parsed
WHERE protocol_name IS NOT NULL
GROUP BY protocol_name
ON CONFLICT (name) DO UPDATE
SET n = existing.n + EXCLUDED.n;

INSERT INTO logs.fail (tried_at, uid, sid, client_ip, tr, rr, pid)
SELECT
    parsed.tried_at,
    username.id,
    sourceip.id,
    parsed.client_ip,
    parsed.tr,
    parsed.rr,
    protocol.id
FROM fail_log_parsed AS parsed
LEFT JOIN logs.username AS username
    ON username.name = parsed.username
LEFT JOIN logs.sourceip AS sourceip
    ON sourceip.addr = parsed.source_addr
LEFT JOIN logs.protocol AS protocol
    ON protocol.name = parsed.protocol_name;

COMMIT;
